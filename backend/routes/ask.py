"""Natural-language → SQL → summarization endpoint.

Uses the modern openai>=1.0 SDK (client.chat.completions.create).
Model defaults to gpt-6-luna (OpenAI's listed replacement for the
deprecated gpt-4o-mini). Override with the OPENAI_MODEL env var.

The SQL generated by the LLM is passed through `sql_safety.sanitize_llm_sql`
before execution: markdown fences are stripped, only the first statement
is kept, and anything that isn't SELECT / WITH / SHOW is rejected with a
400. A WITH statement must end in a SELECT main statement (MySQL allows
CTEs before writes), and INTO OUTFILE / INTO DUMPFILE are rejected. This
is a defense-in-depth control, not a substitute for giving the backend
its own read-only MySQL user.
"""

from __future__ import annotations

import hashlib
import logging
import os

from fastapi import APIRouter, HTTPException
from fastapi.responses import JSONResponse
from openai import OpenAI

from db import get_connection
from sql_safety import UnsafeSQLError, sanitize_llm_sql

log = logging.getLogger(__name__)


_MODEL = os.getenv("OPENAI_MODEL", "gpt-6-luna")
_client: OpenAI | None = None


def _get_client() -> OpenAI:
    global _client
    if _client is None:
        api_key = os.getenv("OPENAI_API_KEY")
        if not api_key:
            raise HTTPException(
                status_code=500,
                detail="OPENAI_API_KEY environment variable is not set.",
            )
        _client = OpenAI(api_key=api_key)
    return _client


router = APIRouter()


def _ask_llm(system_prompt: str, user_prompt: str) -> str:
    """Single-turn chat completion helper."""
    client = _get_client()
    resp = client.chat.completions.create(
        model=_MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    )
    return (resp.choices[0].message.content or "").strip()


@router.post("/ask")
async def ask_question(payload: dict):
    if "question" not in payload:
        raise HTTPException(status_code=400, detail="Field 'question' is required.")
    question = payload["question"]

    # 1. Generate SQL query from natural language.
    raw_sql = _ask_llm(
        system_prompt=(
            "You generate MySQL SQL queries. Return a single read-only "
            "statement (SELECT, WITH, or SHOW). Do not wrap the query in "
            "Markdown code fences. Do not add an explanation."
        ),
        user_prompt=(
            "Generate an SQL query for MySQL based on the following user "
            "question. Use the 'cost_data' or 'cost_summary' tables. "
            f"Question: \"{question}\". "
            "Return only the SQL query without additional explanation."
        ),
    )

    # 2. Sanitize the LLM output before executing it. Anything that
    #    isn't a single read-only statement is rejected with a 400;
    #    never reaches the database.
    try:
        sql_query = sanitize_llm_sql(raw_sql)
    except UnsafeSQLError as exc:
        # Log only a fingerprint of the rejected SQL — the raw text can
        # echo user-supplied content (prompt-injected output) into logs.
        log.warning(
            "Rejecting LLM-generated SQL on /ask. reason=%s len=%d sha256=%s",
            exc,
            len(raw_sql),
            hashlib.sha256(raw_sql.encode("utf-8", "replace")).hexdigest()[:16],
        )
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    # 3. Execute SQL against the database.
    conn = get_connection()
    try:
        cursor = conn.cursor()
        try:
            cursor.execute(sql_query)
            rows = cursor.fetchall()
            columns = [desc[0] for desc in cursor.description] if cursor.description else []
            data = [dict(zip(columns, row)) for row in rows]
        finally:
            cursor.close()
    finally:
        conn.close()

    # 4. Summarize results via LLM.
    answer = _ask_llm(
        system_prompt="You provide concise AWS cost insights.",
        user_prompt=(
            "You are an AWS cost analysis assistant. "
            "Use the following query results to answer the user's question.\n"
            f"Question: \"{question}\"\n"
            f"Data: {data}"
        ),
    )

    return JSONResponse(
        {
            "answer": answer,
            "data": data,
            "sql": sql_query,
        }
    )